        authorityBoundary: surface.authorityBoundary,
        doAuthority: false,
        liveProviderReads: false,
      });
    }

    export function createContinuousDevotionalPlayer(raw, episodeId, options = {}) {
      const surface = parseHumanSurface(raw);
      assertNoDoAuthority(surface);
      const queue = devotionalQueue(surface, episodeId);

      if (!queue) throw new Error("Unknown devotional episode: " + String(episodeId));
      if (queue.continuousPlay !== true || queue.playbackPolicy !== "STRAIGHT_THROUGH") {
        throw new Error("Devotional episode is not admitted for straight-through playback");
      }

      const adapter = options.adapter ?? createTimedDemoPlaybackAdapter();
      const listeners = new Set();
      let currentHandle = null;
      let runPromise = null;
      let cancelled = false;
      let state = Object.freeze({
        status: "IDLE",
        episodeId,
        index: -1,
        segmentRef: null,
        receipt: null,
      });

      const emit = (next) => {
        state = Object.freeze({ ...state, ...next });
        for (const listener of listeners) listener(state);
      };

      async function run() {
        cancelled = false;

        for (let index = 0; index < queue.segments.length; index += 1) {
          if (cancelled) break;

          const segment = queue.segments[index];
          currentHandle = adapter.open(segment);
          if (!currentHandle || typeof currentHandle.play !== "function") {
            throw new TypeError("playback adapter must return a handle with play()");
          }

          emit({
            status: "PLAYING",
            index,
            segmentRef: segment.ref,
            receipt: null,
          });

          await currentHandle.play();
          currentHandle = null;
        }

        if (!cancelled) {
          const receipt = Object.freeze({
            kind: "LOCAL_PLAYBACK_COMPLETED",
            episodeId,
            segmentRefs: Object.freeze(queue.segments.map((segment) => segment.ref)),
            externalEffects: false,
            authorityBoundary: "OBSERVE",
            doAuthority: false,
          });

          emit({
            status: "COMPLETED",
            index: queue.segments.length - 1,
            segmentRef: queue.segments.at(-1)?.ref ?? null,
            receipt,
          });
        }

        runPromise = null;
        return state;
      }

      return Object.freeze({
        snapshot() {
          return state;
        },
        subscribe(listener) {
          if (typeof listener !== "function") throw new TypeError("listener must be a function");
          listeners.add(listener);
          listener(state);
          return () => listeners.delete(listener);
        },
        start() {
          if (!runPromise) runPromise = run();
          return runPromise;
        },
        pause() {
          if (state.status !== "PLAYING" || !currentHandle?.pause) return state;
          currentHandle.pause();
          emit({ status: "PAUSED" });
          return state;
        },
        resume() {
          if (state.status !== "PAUSED" || !currentHandle?.resume) return state;
          currentHandle.resume();
          emit({ status: "PLAYING" });
          return state;
        },
        stop() {
          cancelled = true;
          currentHandle?.stop?.();
          currentHandle = null;
          emit({ status: "STOPPED", receipt: null });
          return state;
        },
      });
    }

    export function createTimedDemoPlaybackAdapter(options = {}) {
      const millisPerSecond = options.millisPerSecond ?? 1;

      return Object.freeze({
        open(segment) {
          let remaining = Math.max(0, segment.durationSeconds * millisPerSecond);
          let timer = null;
          let startedAt = null;
          let settled = false;
          let resolveDone;

          const done = new Promise((resolve) => {
            resolveDone = resolve;
          });

          const arm = () => {
            if (settled) return;
            startedAt = Date.now();
            timer = setTimeout(() => {
              settled = true;
              timer = null;
              remaining = 0;
              resolveDone();
            }, remaining);
          };

          return Object.freeze({
            play() {
              if (!settled && timer === null) arm();
              return done;
            },
            pause() {
              if (settled || timer === null) return;
              clearTimeout(timer);
              timer = null;
              remaining = Math.max(0, remaining - (Date.now() - startedAt));
            },
            resume() {
              if (!settled && timer === null) arm();
              return done;
            },
            stop() {
              if (timer !== null) clearTimeout(timer);
              timer = null;
              if (!settled) {
                settled = true;
                resolveDone();
              }
            },
          });
        },
      });
    }

    export function createHtmlAudioAdapter(options = {}) {
      const resolveAudioRef = options.resolveAudioRef ?? ((audioRef) => audioRef);
      const audioFactory =
        options.audioFactory ??
        ((src) => {
          if (typeof Audio !== "function") {
            throw new Error("HTML Audio is unavailable; provide audioFactory");
          }
          return new Audio(src);
        });

      return Object.freeze({
        open(segment) {
          if (!segment.audioRef) {
            return createTimedDemoPlaybackAdapter({ millisPerSecond: 0 }).open(segment);
          }

          const src = resolveAudioRef(segment.audioRef, segment);
          if (!src) throw new Error("No admitted media source for " + segment.audioRef);

          const audio = audioFactory(src, segment);
          let settled = false;
          let resolveDone;
          let rejectDone;
          const done = new Promise((resolve, reject) => {
            resolveDone = resolve;
            rejectDone = reject;
          });

          const cleanup = () => {
            audio.removeEventListener?.("ended", onEnded);
            audio.removeEventListener?.("error", onError);
          };
          const onEnded = () => {
            if (settled) return;
            settled = true;
            cleanup();
            resolveDone();
          };
          const onError = (event) => {
            if (settled) return;
            settled = true;
            cleanup();
            rejectDone(event instanceof Error ? event : new Error("audio playback failed"));
          };

          audio.addEventListener?.("ended", onEnded);
          audio.addEventListener?.("error", onError);

          return Object.freeze({
            async play() {
              await audio.play();
              return done;
            },
            pause() {
              audio.pause();
            },
            async resume() {
              await audio.play();
              return done;
            },
            stop() {
              audio.pause();
              try {
                audio.currentTime = 0;
              } catch {
                // Some injected media handles expose read-only currentTime.
              }
              if (!settled) {
                settled = true;
                cleanup();
                resolveDone();
              }
            },
          });
        },
      });
    }

