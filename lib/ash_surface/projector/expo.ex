defmodule AshSurface.Projector.Expo do
  @moduledoc """
  Projector for React Native / Expo applications (ZOELA consumer substrate).

  Manufactures:
  - `{prefix}.schemas.mjs`: Pre-compiled Zod input & output boundary schemas
  - `{prefix}.actions.mjs`: Machine-discoverable MX action descriptors with explicit authority boundaries
  - `{prefix}.events.mjs`: Read-only realtime observation & event projections
  - `{prefix}.receipts.mjs`: MX receipt envelope and reconciliation primitives
  - `{prefix}.mjs`: Executable client runtime factory pre-bound with manufactured schemas
  - `{prefix}.tanstack.mjs`: TanStack Query mutation adapter

  The ZOE / DfCM member-facing `{prefix}.human.mjs` and `{prefix}.demo.mjs`
  artifacts are NOT emitted here: they are a devotional-product projection and
  live in the separate `ash_surface_zoe` package
  (`AshSurfaceZoe.Projector.Human`, packages/ash_surface_zoe).
  """

  @behaviour AshSurface.Projector.IR

  @identifier ~r/\A[A-Za-z_$][A-Za-z0-9_$]*\z/

  @doc """
  Projects a surface carried as `ash_surface.surface` IR (see
  `AshSurface.Projector.IR.from_surface/1`) into the Expo artifact set.

  The surface is recovered with `AshSurface.Projector.IR.to_surface/1`, which
  re-verifies its digest; other IR kinds are refused with typed errors.
  """
  @impl true
  @spec project_ir(AshSurface.Projector.IR.input(), keyword()) ::
          {:ok, %{optional(String.t()) => String.t()}, map()} | {:error, term()}
  def project_ir(irs, opts \\ []) do
    with {:ok, surface} <- AshSurface.Projector.IR.to_surface(irs) do
      project_surface(surface, opts)
    end
  end

  defp project_surface(%AshSurface.Surface{} = surface, opts) do
    prefix = Keyword.get(opts, :prefix, "zoela_surface")
    target_dir = Keyword.get(opts, :target_dir)

    actions = get_in(surface.contract, ["surface", "actions"]) || []
    resources = get_in(surface.contract, ["manifest", "resources"]) || %{}

    with {:ok, schemas_code} <- render_schemas(actions, resources),
         {:ok, actions_code} <- render_actions(actions) do
      events_code = render_events()
      receipts_code = render_receipts()
      client_code = render_client(prefix)
      tanstack_code = render_tanstack(actions, prefix)

      artifacts = %{
        "#{prefix}.schemas.mjs" => schemas_code,
        "#{prefix}.actions.mjs" => actions_code,
        "#{prefix}.events.mjs" => events_code,
        "#{prefix}.receipts.mjs" => receipts_code,
        "#{prefix}.mjs" => client_code,
        "#{prefix}.tanstack.mjs" => tanstack_code
      }

      if target_dir do
        File.mkdir_p!(target_dir)

        Enum.each(artifacts, fn {filename, content} ->
          File.write!(Path.join(target_dir, filename), content)
        end)
      end

      {:ok, artifacts, %{prefix: prefix, action_count: length(actions)}}
    end
  end

  # Input schema per action: a resolvable resource's WRITABLE, public
  # attributes (the action's accepted inputs, as Compiler.Section.Schema's
  # inputs: private/generated fields such as id / inserted_at are excluded);
  # a field with a default or nil-able is omittable. An action naming a
  # resource the manifest does not carry is a typed error, never an empty
  # passthrough object that accepts anything. An action naming no resource
  # makes no input claim and keeps the empty passthrough object.
  defp render_schemas(actions, resources) do
    with {:ok, names} <- schema_names(actions),
         {:ok, blocks} <- schema_blocks(actions, names, resources) do
      {:ok,
       """
       // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
       // Do not edit directly; modify authoritative Ash resources or ontology instead.

       import { z } from "zod";

       #{Enum.join(blocks, "\n\n")}

       export const SCHEMAS = {
       #{Enum.map_join(actions, ",\n", fn a -> "  #{object_key(a["id"])}: { input: #{names[a["id"]]}_inputSchema, output: #{names[a["id"]]}_outputSchema }" end)}
       };
       """}
    end
  end

  defp schema_blocks(actions, names, resources) do
    Enum.reduce_while(actions, {:ok, []}, fn action, {:ok, acc} ->
      id = action["id"]

      with {:ok, fields} <- action_fields(action, resources),
           input = object_expression(fields),
           :ok <- admit_zod(id, input) do
        safe = names[id]

        block = """
        export const #{safe}_inputSchema = #{input};

        export const #{safe}_outputSchema = z.object({
          success: z.boolean(),
          data: z.record(z.string(), z.unknown()).optional(),
          receiptRef: z.string().optional(),
          error: z.string().optional()
        }).passthrough();
        """

        {:cont, {:ok, [block | acc]}}
      else
        {:error, _} = e -> {:halt, e}
      end
    end)
    |> case do
      {:ok, acc} -> {:ok, Enum.reverse(acc)}
      e -> e
    end
  end

  defp admit_zod(id, text) do
    case AshSurface.Projectors.JS.ZodGuard.expression(text) do
      :ok -> :ok
      {:error, reason} -> {:error, {:zod_refused, id, reason}}
    end
  end

  defp action_fields(%{"resource" => nil}, _resources), do: {:ok, []}

  defp action_fields(%{"resource" => name, "id" => id}, resources) do
    case find_resource(resources, name) do
      %{"fields" => f} when is_map(f) ->
        {:ok, f |> Enum.filter(&input_field?/1) |> Enum.sort_by(fn {k, _} -> to_string(k) end)}

      %{"fields" => []} ->
        {:ok, []}

      nil ->
        {:error, {:unknown_resource, id, name}}

      other ->
        {:error, {:resource_without_fields, id, name, other}}
    end
  end

  defp action_fields(_action, _resources), do: {:ok, []}

  # Writable, public input attributes. A hand-built field without manifest
  # facts (no "writable"/"kind"/"private") is an input.
  defp input_field?({_name, %{} = fdef}) do
    Map.get(fdef, "writable") != false and Map.get(fdef, "writable?") != false and
      Map.get(fdef, "private?") != true and Map.get(fdef, "private") != true and
      Map.get(fdef, "public?") != false and
      Map.get(fdef, "kind", "attribute") in ["attribute", nil]
  end

  defp input_field?(_), do: false

  defp object_expression(fields) do
    body =
      Enum.map_join(fields, ",\n", fn {fname, fdef} ->
        "  #{object_key(fname)}: #{map_zod_type(omittable_input(fdef))}"
      end)

    "z.object({\n#{body}\n}).passthrough()"
  end

  # Collision-free, JS-identifier-safe stem per action id. Non-identifier
  # characters map to `_`; a leading digit gains a `_` prefix; ids whose stems
  # collide ALL gain a short stable hash suffix (order independent).
  defp schema_names(actions) do
    with :ok <- check_ids(actions) do
      ids = Enum.map(actions, & &1["id"])
      stems = Map.new(ids, &{&1, sanitize_identifier(&1)})
      counts = stems |> Map.values() |> Enum.frequencies()

      names =
        Map.new(stems, fn {id, stem} ->
          if counts[stem] > 1, do: {id, stem <> "_" <> short_hash(id)}, else: {id, stem}
        end)

      if names |> Map.values() |> Enum.uniq() |> length() == map_size(names),
        do: {:ok, names},
        else: {:error, {:schema_name_collision, names}}
    end
  end

  defp check_ids(actions) do
    Enum.reduce_while(actions, MapSet.new(), fn a, seen ->
      case a do
        %{"id" => id} when is_binary(id) and id != "" ->
          if MapSet.member?(seen, id),
            do: {:halt, {:error, {:duplicate_action_id, id}}},
            else: {:cont, MapSet.put(seen, id)}

        other ->
          {:halt, {:error, {:action_without_id, other}}}
      end
    end)
    |> case do
      {:error, _} = e -> e
      _ -> :ok
    end
  end

  defp short_hash(id),
    do: :crypto.hash(:sha256, id) |> Base.encode16(case: :lower) |> binary_part(0, 8)

  # The delegated boundary lookup emitted below FAILS CLOSED
  # (finish-tripwires-024): an id that admits no descriptor has no delegated
  # boundary, so `getAuthorityBoundary` answers null — the v26.9.16 law
  # (absent == not delegated == null) extended to the absent action. The
  # former `: "OBSERVE"` fallback fabricated the safest-sounding boundary for
  # an unknown id on the delegated lookup path; unknown ≠ OBSERVE. Enforced by
  # ExpoActionsTest's TRIPWIRE over the rendered artifact.
  defp render_actions(actions) do
    with :ok <- check_proto(actions) do
      {:ok, render_actions_code(actions |> canonical() |> Jason.encode!(pretty: true))}
    end
  end

  # A `"__proto__"` key in a JS object literal sets the prototype instead of
  # an own property, so the embedded ACTIONS literal refuses it.
  defp check_proto(%{} = m) do
    Enum.find_value(m, :ok, fn {k, v} ->
      if to_string(k) == "__proto__",
        do: {:error, {:proto_key_refused, "ACTIONS"}},
        else: nil_ok(check_proto(v))
    end)
  end

  defp check_proto(l) when is_list(l), do: Enum.find_value(l, :ok, &nil_ok(check_proto(&1)))
  defp check_proto(_), do: :ok

  defp nil_ok(:ok), do: nil
  defp nil_ok(err), do: err

  # Maps are emitted key-sorted (map iteration order is hash order past 32 keys).
  defp canonical(%{} = m),
    do:
      m
      |> Enum.map(fn {k, v} -> {to_string(k), canonical(v)} end)
      |> Enum.sort()
      |> Jason.OrderedObject.new()

  defp canonical(l) when is_list(l), do: Enum.map(l, &canonical/1)
  defp canonical(v), do: v

  defp render_actions_code(actions_json) do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
    // Explicit authority boundaries and semantic identities for machine discoverability.

    export const ACTIONS = Object.freeze(#{actions_json});

    export function getAction(id) {
      return ACTIONS.find((a) => a.id === id) ?? null;
    }

    export function hasDoAuthority(id) {
      const action = getAction(id);
      return action ? action.doAuthority === true : false;
    }

    export function getAuthorityBoundary(id) {
      const action = getAction(id);
      return action ? action.authorityBoundary : null;
    }
    """
  end

  defp render_events do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
    // Read-only realtime observation and event projection layer.

    import { z } from "zod";

    export const eventProjectionSchema = z.object({
      eventId: z.string().min(1),
      sequence: z.number().int().nonnegative(),
      subjectRef: z.string().min(1),
      eventType: z.string().min(1),
      stateDigest: z.string().min(1),
      evidenceRef: z.string().nullable().optional(),
      receiptRef: z.string().nullable().optional(),
      payload: z.record(z.string(), z.unknown()).nullable().optional(),
      occurredAt: z.string().min(1),
      authorityBoundary: z.literal("OBSERVE").default("OBSERVE"),
    }).passthrough();

    export function parseEvent(raw) {
      return eventProjectionSchema.parse(raw);
    }
    """
  end

  defp render_receipts do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
    // MX Consequence Receipt Envelope & Offline Reconciliation Protocol.
    //
    // receiptHash integrity law (chicago-receipthash-038). receiptHash is NOT
    // free-form: it is the lowercase-hex SHA-256 of receiptHashPreimage(receipt)
    // — canonical JSON over the envelope's named content fields, EXCLUDING
    // receiptHash itself. The content-field list hashed:
    //   episodeId, correlationId, exactSubject, actionId, semanticActionId,
    //   authorityBoundary, actorRef, preStateDigest, inputDigest, policyRef,
    //   taskNetworkRef, transportReceipt, domainReceiptRef, evidenceRefs,
    //   outcome, postStateDigest, standingBefore, standingAfter, replayKey,
    //   timestamp
    // The runtime transport receipt mints the same law over its named payload:
    //   actionId, input, consequence, dispatchState, selectedTransport,
    //   timestamp
    // Canonical bytes: recursively key-sorted objects, order-preserving arrays
    // (`canonicalStringify` below; Elixir twin `AshSurface.CanonicalJSON`).
    // Any field reorder therefore leaves the hash unchanged; any value change
    // must move it.

    import { z } from "zod";

    export const mxReceiptSchema = z.object({
      episodeId: z.string().min(1),
      correlationId: z.string().min(1),
      exactSubject: z.string().min(1),
      actionId: z.string().min(1),
      semanticActionId: z.string().min(1),
      authorityBoundary: z.enum(["OBSERVE", "SELECT", "CONSTRUCT", "DO"]),
      actorRef: z.string().optional(),
      preStateDigest: z.string().optional(),
      inputDigest: z.string().min(1),
      policyRef: z.string().optional(),
      taskNetworkRef: z.string().optional(),
      transportReceipt: z.record(z.string(), z.unknown()),
      domainReceiptRef: z.string().optional(),
      evidenceRefs: z.array(z.string()).default([]),
      outcome: z.enum(["COMPLETED", "REFUSED", "UNKNOWN_AFTER_DISPATCH"]),
      postStateDigest: z.string().optional(),
      standingBefore: z.string().optional(),
      standingAfter: z.string().optional(),
      replayKey: z.string().min(1),
      // Integrity commitment over the content fields above (never over this
      // slot): lowercase-hex sha256 of receiptHashPreimage(receipt).
      receiptHash: z.string().min(64),
      timestamp: z.string().min(1),
    }).passthrough();

    export function canonicalStringify(obj) {
      if (obj === null || typeof obj !== "object") return JSON.stringify(obj);
      if (Array.isArray(obj)) return `[${obj.map(canonicalStringify).join(",")}]`;
      const keys = Object.keys(obj).sort();
      return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalStringify(obj[k])}`).join(",")}}`;
    }

    // Verification-only preimage of the receiptHash integrity law: canonical
    // JSON bytes over every named content field of the receipt EXCEPT the
    // receiptHash slot itself. Hashing stays with the platform crypto provider
    // (SubtleCrypto / node:crypto): receiptHash is sha256(preimage) rendered
    // as lowercase hex. Nothing is constructed, assigned, or signed here.
    export function receiptHashPreimage(receipt) {
      if (receipt === null || typeof receipt !== "object" || Array.isArray(receipt)) {
        throw new TypeError("receiptHashPreimage: receipt must be an envelope object");
      }
      const content = { ...receipt };
      delete content.receiptHash;
      return canonicalStringify(content);
    }
    """
  end

  defp render_client(prefix) do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
    // Complete, executable client manufactured with pre-bound Zod boundary schemas.
    // Requires ash_surface_runtime.mjs and ash_surface_http_transport.mjs beside this file.

    import { createClient } from "./ash_surface_runtime.mjs";
    import { createHttpTransport } from "./ash_surface_http_transport.mjs";
    import { SCHEMAS } from "./#{prefix}.schemas.mjs";
    import { ACTIONS } from "./#{prefix}.actions.mjs";

    // Reconcile is the runtime's: client.reconcile validates the adapter reply
    // with reconcileResultSchema and emits reconcile.result. reconcileEndpoint is
    // sugar that supplies a reconcile-only HTTP adapter (never selected for
    // dispatch) when no http transport carries one. Adapter failures throw.
    export function createZoelaClient({
      contract,
      transports = {},
      prefer = "http",
      schemas = SCHEMAS,
      reconcileEndpoint,
      reconcileBaseUrl,
      reconcileAllowedOrigins,
      reconcileTimeoutMs = 10000,
      ...rest
    }) {
      let wiredTransports = transports;
      let sugar = false;
      if (reconcileEndpoint && typeof transports.http?.reconcile !== "function") {
        const timed = (url, init) =>
          fetch(url, { ...init, signal: init?.signal ?? AbortSignal.timeout(reconcileTimeoutMs) });
        // Origin law (transport rule intact): the caller's explicit reconcileEndpoint
        // authorizes exactly its own origin when absolute; a relative endpoint needs a
        // page origin or reconcileBaseUrl. reconcileAllowedOrigins adds further origins.
        let ownOrigin = [];
        try {
          ownOrigin = [new URL(reconcileEndpoint).origin];
        } catch {
          // relative endpoint: resolved against the page or reconcileBaseUrl by the transport
        }
        const { reconcile } = createHttpTransport({
          endpoint: reconcileEndpoint,
          customFetch: timed,
          csrf: false,
          baseUrl: reconcileBaseUrl,
          allowedOrigins: [...ownOrigin, ...(reconcileAllowedOrigins ?? [])],
        });
        wiredTransports = { ...transports, http: { available: false, invoke: undefined, ...transports.http, reconcile } };
        sugar = true;
      }

      const client = createClient({
        ...rest,
        contract,
        transports: wiredTransports,
        prefer,
        schemas,
      });

      return Object.freeze({
        ...client,
        actionsMetadata: ACTIONS,
        reconcile: (commandId, transportName) =>
          client.reconcile(commandId, transportName ?? (sugar ? "http" : prefer)),
      });
    }
    """
  end

  defp render_tanstack(_actions, prefix) do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.10.8)
    // TanStack Query cache adapter for Expo / React Native.

    import { getAction } from "./#{prefix}.actions.mjs";

    export const queryKeys = {
      all: ["ash_surface"],
      resource: (res) => ["ash_surface", res],
      action: (res, act) => ["ash_surface", res, act],
    };

    export function createMutationOptions(client, actionId) {
      const meta = getAction(actionId);
      const action = client.get(actionId);

      return {
        mutationKey: queryKeys.action(meta?.resource, meta?.action),
        mutationFn: async (input) => {
          return await action.invokeWithReceipt(input);
        }
      };
    }
    """
  end

  # Twinned with Compiler.Section.Schema: Ash accepts an omitted input when it
  # is nil-able, so a nil-able field is `.nullable().optional()` here too.
  defp omittable_input(fdef) do
    nil_ok? = Map.get(fdef, "allow_nil?") == true or Map.get(fdef, "allow_nil") == true

    if nil_ok? or Map.get(fdef, "has_default") == true or Map.get(fdef, "has_default?") == true,
      do: fdef |> Map.put("allow_nil?", nil_ok?) |> Map.put("optional", true),
      else: fdef
  end

  # Delegates to the shared AshSurface.Compiler.ZodType table (single source).
  defp map_zod_type(definition), do: AshSurface.Compiler.ZodType.fragment(definition)

  defp find_resource(resources, name) when is_map(resources) do
    Enum.find_value(resources, fn
      {_k, %{"name" => ^name} = r} -> r
      {_k, %{"module" => ^name} = r} -> r
      _ -> nil
    end)
  end

  defp find_resource(resources, name) when is_list(resources) do
    Enum.find(resources, fn
      %{"name" => ^name} -> true
      %{"module" => ^name} -> true
      _ -> false
    end)
  end

  defp find_resource(_, _), do: nil

  # `__proto__` is a computed key: a literal `"__proto__":` sets the prototype.
  defp object_key(name) do
    name = to_string(name)

    cond do
      name == "__proto__" -> ~s(["__proto__"])
      Regex.match?(@identifier, name) -> name
      true -> Jason.encode!(name)
    end
  end

  defp sanitize_identifier(id) do
    stem = String.replace(id, ~r/[^a-zA-Z0-9_]/, "_")
    if Regex.match?(~r/\A[0-9]/, stem), do: "_" <> stem, else: stem
  end
end
