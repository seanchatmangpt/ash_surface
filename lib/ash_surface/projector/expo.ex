  defp render_receipts do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.9.17)
    // MX Consequence Receipt Envelope & Offline Reconciliation Protocol.
    //
    // receiptHash integrity law (chicago-receipthash-038). receiptHash is NOT
    // free-form: it is the lowercase-hex SHA-256 of receiptHashPreimage(receipt)
    // — canonical JSON over the envelope's named content fields, EXCLUDING
    // receiptHash itself. The content-field list hashed:
    //   episodeId, correlationId, exactSubject, actionId, semanticActionId,
    //   authorityBoundary, actorRef, preStateDigest, inputDigest, policyRef,
    //   taskNetworkRef, transportReceipt, domainReceiptRef, evidenceRefs,
    //   outcome, postStateDigest, standingBefore, standingAfter, replayKey,
    //   timestamp
    // The runtime transport receipt mints the same law over its named payload:
    //   actionId, input, consequence, dispatchState, selectedTransport,
    //   timestamp
    // Canonical bytes: recursively key-sorted objects, order-preserving arrays
    // (`canonicalStringify` below; Elixir twin `AshSurface.CanonicalJSON`).
    // Any field reorder therefore leaves the hash unchanged; any value change
    // must move it.

    import { z } from "zod";

    export const mxReceiptSchema = z.object({
      episodeId: z.string().min(1),
      correlationId: z.string().min(1),
      exactSubject: z.string().min(1),
      actionId: z.string().min(1),
      semanticActionId: z.string().min(1),
      authorityBoundary: z.enum(["OBSERVE", "SELECT", "CONSTRUCT", "DO"]),
      actorRef: z.string().optional(),
      preStateDigest: z.string().optional(),
      inputDigest: z.string().min(1),
      policyRef: z.string().optional(),
      taskNetworkRef: z.string().optional(),
      transportReceipt: z.record(z.string(), z.unknown()),
      domainReceiptRef: z.string().optional(),
      evidenceRefs: z.array(z.string()).default([]),
      outcome: z.enum(["COMPLETED", "REFUSED", "UNKNOWN_AFTER_DISPATCH"]),
      postStateDigest: z.string().optional(),
      standingBefore: z.string().optional(),
      standingAfter: z.string().optional(),
      replayKey: z.string().min(1),
      // Integrity commitment over the content fields above (never over this
      // slot): lowercase-hex sha256 of receiptHashPreimage(receipt).
      receiptHash: z.string().min(64),
      timestamp: z.string().min(1),
    }).passthrough();

    export function canonicalStringify(obj) {
      if (obj === null || typeof obj !== "object") return JSON.stringify(obj);
      if (Array.isArray(obj)) return `[${obj.map(canonicalStringify).join(",")}]`;
      const keys = Object.keys(obj).sort();
      return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalStringify(obj[k])}`).join(",")}}`;
    }

    // Verification-only preimage of the receiptHash integrity law: canonical
    // JSON bytes over every named content field of the receipt EXCEPT the
    // receiptHash slot itself. Hashing stays with the platform crypto provider
    // (SubtleCrypto / node:crypto): receiptHash is sha256(preimage) rendered
    // as lowercase hex. Nothing is constructed, assigned, or signed here.
    export function receiptHashPreimage(receipt) {
      if (receipt === null || typeof receipt !== "object" || Array.isArray(receipt)) {
        throw new TypeError("receiptHashPreimage: receipt must be an envelope object");
      }
      const content = { ...receipt };
      delete content.receiptHash;
      return canonicalStringify(content);
    }
    """
  end

  defp render_human do
    """
    // @generated by AshSurface.Projector.Expo (CalVer 26.9.21)
    // Human projection helpers. This artifact presents choices and commitments,
    // but cannot acquire DO authority or dispatch a consequence.

    import {
      humanSurfaceSchema,
      parseHumanSurfaceProjection,
    } from "ash_surface";

    export const HUMAN_AREAS = Object.freeze(["TODAY", "BIBLE", "LIFE", "ZOE", "YOU"]);
    export const HUMAN_GRAMMAR = Object.freeze([
      "SEE",
      "UNDERSTAND",
      "EXPLORE",
      "CHOOSE",
      "ACT",
      "LEARN",
    ]);

    export function parseHumanSurface(raw) {
      return parseHumanSurfaceProjection(raw);
    }

    export function getArea(raw, areaName) {
      const surface = humanSurfaceSchema.parse(raw);
      if (!HUMAN_AREAS.includes(areaName)) {
        throw new TypeError("Unknown human area: " + String(areaName));
      }

      return surface[areaName.toLowerCase()];
    }

    export function preservedPossibilities(raw) {
      const surface = humanSurfaceSchema.parse(raw);

      return surface.possibilitySets.flatMap((set) =>
        set.possibilities.filter(
          (option) => option.status === "PRESERVED" || option.status === "CANDIDATE",
        ),
      );
    }

    export function explanationsFor(raw, subjectRef) {
      const surface = humanSurfaceSchema.parse(raw);
      return surface.explanations.filter((explanation) => explanation.subjectRef === subjectRef);
    }

    export function personalizationContext(raw, contextId) {
      const surface = humanSurfaceSchema.parse(raw);
      return surface.personalizationContexts.find((item) => item.contextId === contextId) ?? null;
    }

    export function manufactureTraceFor(raw, artifactRef) {
      const surface = humanSurfaceSchema.parse(raw);
      return surface.manufactureTraces.find((item) => item.artifactRef === artifactRef) ?? null;
    }

    export function devotionalQueue(raw, episodeId) {
      const surface = humanSurfaceSchema.parse(raw);
      const episode = surface.devotionalEpisodes.find((item) => item.episodeId === episodeId);
      if (!episode) return null;

      return Object.freeze({
        episodeId,
        title: episode.title,
        continuousPlay: episode.continuousPlay,
        playbackPolicy: episode.playbackPolicy,
        durationSeconds: episode.durationSeconds,
        segments: Object.freeze([...episode.segments].sort((a, b) => a.position - b.position)),
      });
    }

    export function commitmentPreview(raw, actionRef) {
      const surface = humanSurfaceSchema.parse(raw);
      const boundary = surface.commitmentBoundaries.find((item) => item.actionRef === actionRef);
      if (!boundary) return null;

      return Object.freeze({
        boundaryId: boundary.boundaryId,
        actionRef: boundary.actionRef,
        consequenceSummary: boundary.consequenceSummary,
        externalEffects: Object.freeze([...boundary.externalEffects]),
        reversibility: boundary.reversibility,
        confirmationState: boundary.confirmationState,
        confirmationRequired: boundary.confirmationRequired,
        nextHandoff: boundary.nextHandoff,
        authorityCeiling: boundary.authorityCeiling,
        doAuthority: boundary.doAuthority,
      });
    }

    export function journeyTimeline(raw) {
      const surface = humanSurfaceSchema.parse(raw);

      return Object.freeze(
        surface.journeys
          .flatMap((journey) =>
            journey.entries.map((entry) => ({
              ...entry,
              journeyId: journey.journeyId,
              privacyScope: journey.privacyScope,
            })),
          )
          .sort((left, right) => left.occurredAt.localeCompare(right.occurredAt)),
      );
    }

    export function assertNoDoAuthority(raw) {
      const surface = humanSurfaceSchema.parse(raw);

      if (surface.doAuthority !== false || surface.authorityBoundary !== "OBSERVE") {
        throw new Error("Human surface attempted to exceed OBSERVE authority");
      }

      for (const set of surface.possibilitySets) {
        for (const option of set.possibilities) {
          if (option.doAuthority !== false || option.authorityCeiling === "DO") {
            throw new Error("Possibility " + option.possibilityId + " attempted DO authority");
          }
        }
      }

      for (const context of surface.personalizationContexts) {
        if (
          context.doAuthority !== false ||
          context.authorityBoundary !== "OBSERVE" ||
          context.privacyScope !== "SUBJECT_PRIVATE" ||
          context.shareScope !== "SUBJECT_ONLY"
        ) {
          throw new Error("Personalization context " + context.contextId + " violates privacy/authority");
        }
      }

      for (const trace of surface.manufactureTraces) {
        if (trace.doAuthority !== false || trace.authorityBoundary !== "OBSERVE") {
          throw new Error("Manufacture trace " + trace.traceId + " attempted authority");
        }
      }

      for (const boundary of surface.commitmentBoundaries) {
        if (
          boundary.doAuthority !== false ||
          boundary.authorityCeiling !== "CONSTRUCT" ||
          boundary.nextHandoff !== "BRCE"
        ) {
          throw new Error("Commitment boundary " + boundary.boundaryId + " bypasses BRCE");
        }
      }

      return true;
    }
    """
  end

