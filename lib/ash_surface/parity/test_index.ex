defmodule AshSurface.Parity.TestIndex do
  @moduledoc """
  Structural index of a court file for the parity gate (no code is executed or compiled).

  Elixir files are read through `Code.string_to_quoted/1`, so skip tags are seen however
  they are written (`@tag :skip`, `@tag skip: "..."` across lines, `@tag [skip: true]`,
  `@moduletag [:skip]`, `@describetag`, inline `skip: true`), comments and string literals
  never count as tests, and a `describe` with no active test inside is not a court.

  Each indexed test is `%{title, describe, skipped, has_assert, guarded, asserts}`:

    * `skipped` - skip-tagged at test, describe or module level
    * `tags` - effective tag names (strings) from `@moduletag`, enclosing `@describetag`,
      preceding `@tag` and inline opts, in any literal form
    * `tag_values` - tag name => literal value (`:dynamic` when not a literal); later layers
      override earlier ones. `@tag` binds to the next test only, also across a `describe`
    * `has_assert` - body contains an `assert*`/`refute*` call
    * `guarded` - body or enclosing `if` consults `Code.ensure_loaded?`/`ensure_compiled`
      (a compiled-out guard can make the court a silent no-op)
    * `asserts` - source text of every assertion call (what a `contains` token must hit)

  The index also returns `dynamic`: tests generated by `for` comprehensions or by local
  macros that quote `test` cannot be indexed by title; each is reported as
  `%{reason: "unindexable-dynamic-test", line, title, tag_values, skipped}` rather than a mangled entry. Nested
  `defmodule`s are scoped as separate ExUnit modules.

  JS files (`.mjs`/`.js`) are indexed line-wise (`test/it/describe(` titles, `.skip`/`.todo`,
  `assert`/`expect` lines).
  """

  @type test :: %{
          title: String.t(),
          describe: String.t() | nil,
          skipped: boolean(),
          pending: boolean(),
          tags: [String.t()],
          tag_values: %{optional(String.t()) => term()},
          has_assert: boolean(),
          guarded: boolean(),
          asserts: [String.t()]
        }

  @spec analyze(String.t(), String.t()) ::
          {:ok, %{module_skip: boolean(), tests: [test()], dynamic: [map()]}}
          | {:error, String.t()}
  def analyze(file, body) do
    if Path.extname(file) in [".mjs", ".js"], do: {:ok, js(body)}, else: elixir(body)
  end

  defp elixir(body) do
    case Code.string_to_quoted(body) do
      {:ok, ast} ->
        st =
          walk(ast, %{
            depth: 0,
            module_skip: false,
            describe: nil,
            guard: false,
            dynamic: false,
            acc: [],
            dyn: [],
            macros: macro_names(ast),
            module_tags: %{},
            pending_tags: %{}
          })

        {:ok,
         %{
           module_skip: st.module_skip,
           tests: Enum.reverse(st.acc),
           dynamic: Enum.reverse(st.dyn)
         }}

      {:error, {_, msg, tok}} ->
        {:error, "unparseable Elixir (#{inspect(msg)} #{inspect(tok)})"}
    end
  end

  # names of local macros whose quoted body defines tests (macro-generated tests)
  defp macro_names(ast) do
    {_, acc} =
      Macro.prewalk(ast, [], fn
        {kw, _, [head, [do: body]]} = n, acc when kw in [:defmacro, :defmacrop] ->
          {n, if(defines_test?(body), do: [head_name(head) | acc], else: acc)}

        n, acc ->
          {n, acc}
      end)

    Enum.reject(acc, &is_nil/1)
  end

  defp head_name({:when, _, [h | _]}), do: head_name(h)
  defp head_name({name, _, _}) when is_atom(name), do: name
  defp head_name(_), do: nil

  defp defines_test?(body) do
    {_, found} =
      Macro.prewalk(body, false, fn
        {:quote, _, _} = n, acc -> {n, acc or quoted_test?(n)}
        n, acc -> {n, acc}
      end)

    found
  end

  defp quoted_test?(q) do
    {_, found} =
      Macro.prewalk(q, false, fn
        {kw, _, [_ | _]} = n, _ when kw in [:test, :property] -> {n, true}
        n, acc -> {n, acc}
      end)

    found
  end

  defp walk({:__block__, _, stmts}, st), do: Enum.reduce(stmts, st, &walk/2)

  # a nested module is its own ExUnit module: moduletags, pending @tag and describe state
  # neither leak in nor out
  defp walk({:defmodule, _, [_, [do: body]]}, st) do
    inner =
      walk(body, %{
        st
        | depth: st.depth + 1,
          describe: nil,
          module_skip: false,
          module_tags: %{},
          pending_tags: %{}
      })

    %{
      inner
      | depth: st.depth,
        describe: st.describe,
        module_skip: st.module_skip,
        module_tags: st.module_tags,
        pending_tags: st.pending_tags
    }
  end

  defp walk({:@, _, [{:moduletag, _, [v]}]}, st) do
    st = %{st | module_tags: merge(st.module_tags, v)}
    if st.depth <= 1 and skip?(v), do: %{st | module_skip: true}, else: st
  end

  defp walk({:@, _, [{:tag, _, [v]}]}, st), do: %{st | pending_tags: merge(st.pending_tags, v)}

  defp walk({:@, _, [{:describetag, _, [v]}]}, %{describe: %{} = d} = st),
    do: %{st | describe: %{d | tags: merge(d.tags, v)}}

  # ExUnit attaches `@tag` to the next test only; a `@tag` written before `describe` stays
  # pending and is consumed by the first test inside the describe (verified on a real run)
  defp walk({:describe, _, [title, [do: body]]}, st) do
    d = %{title: title_of(title), tags: %{}}
    inner = walk(body, %{st | describe: d})
    %{inner | describe: nil}
  end

  defp walk({kw, meta, [title | rest]}, st) when kw in [:test, :property, :it] do
    {opts, block} = split_args(rest)
    d = st.describe
    tv = effective_tags(st, opts)
    asserts = assertions(block)

    if st.dynamic do
      dyn = %{
        reason: "unindexable-dynamic-test",
        line: meta[:line],
        title: Macro.to_string(title),
        tag_values: tv,
        skipped: skip_value?(Map.get(tv, "skip"))
      }

      %{st | dyn: [dyn | st.dyn], pending_tags: %{}}
    else
      t = %{
        title: title_of(title),
        describe: d && d.title,
        skipped: skip_value?(Map.get(tv, "skip")),
        pending: block == [],
        tags: Enum.sort(for({k, v} <- tv, v not in [false, nil], do: k)),
        tag_values: tv,
        has_assert: asserts != [],
        guarded: st.guard or guarded?(block),
        asserts: asserts
      }

      %{st | acc: [t | st.acc], pending_tags: %{}}
    end
  end

  defp walk({kw, _, [cond, blocks]}, st) when kw in [:if, :unless] and is_list(blocks) do
    inner = %{st | guard: st.guard or guarded?(cond)}

    st2 =
      blocks
      |> Keyword.take([:do, :else])
      |> Keyword.values()
      |> Enum.reduce(inner, &walk/2)

    %{st2 | guard: st.guard}
  end

  # tests generated by a comprehension are not indexable by title
  defp walk({:for, _, args}, st) when is_list(args) do
    case List.last(args) do
      [do: body] ->
        st2 = walk(body, %{st | dynamic: true})
        %{st2 | dynamic: st.dynamic}

      _ ->
        st
    end
  end

  # call of a local macro that quotes `test`: the generated test is invisible to the index
  defp walk({name, meta, args} = n, st) when is_atom(name) and is_list(args) do
    if name in st.macros do
      tv = effective_tags(st, [])

      dyn = %{
        reason: "unindexable-dynamic-test",
        line: meta[:line],
        title: Macro.to_string(n),
        tag_values: tv,
        skipped: skip_value?(Map.get(tv, "skip"))
      }

      %{st | dyn: [dyn | st.dyn], pending_tags: %{}}
    else
      st
    end
  end

  defp walk(_, st), do: st

  defp split_args(rest) do
    {block, pre} =
      case List.last(rest) do
        [do: _] = b -> {b, Enum.drop(rest, -1)}
        _ -> {[], rest}
      end

    {pre, block}
  end

  # later layers override earlier ones: module < describe < pending @tag < inline opts
  defp effective_tags(st, opts) do
    d = (st.describe && st.describe.tags) || %{}

    st.module_tags
    |> Map.merge(d)
    |> Map.merge(st.pending_tags)
    |> merge(opts)
  end

  # tag map (name => literal value, or :dynamic) from `:slow`, `slow: true`,
  # `[:slow, skip: "x"]`
  defp merge(map, a), do: Enum.reduce(tag_pairs(a), map, fn {k, v}, m -> Map.put(m, k, v) end)

  defp tag_pairs(a) when is_atom(a) and a not in [nil, true, false],
    do: [{Atom.to_string(a), true}]

  defp tag_pairs({k, v}) when is_atom(k), do: [{Atom.to_string(k), lit(v)}]
  defp tag_pairs(l) when is_list(l), do: Enum.flat_map(l, &tag_pairs/1)
  defp tag_pairs(_), do: []

  defp lit(v) when is_atom(v) or is_binary(v) or is_number(v), do: v
  defp lit(_), do: :dynamic

  # `@tag :skip`, `@tag skip: "x"`, `@tag [skip: true]`, `@moduletag [:skip]`
  defp skip?(v),
    do: skip_value?(v |> tag_pairs() |> List.keyfind("skip", 0, {nil, nil}) |> elem(1))

  defp skip_value?(v), do: v not in [false, nil]

  defp title_of(t) when is_binary(t), do: t

  defp title_of({:<<>>, _, parts}),
    do: Enum.map_join(parts, fn p -> if is_binary(p), do: p, else: "\u0000" end)

  defp title_of(_), do: ""

  defp assertions(block) do
    {_, acc} =
      Macro.prewalk(block, [], fn
        {name, _, args} = n, acc when is_atom(name) and is_list(args) ->
          if assertion_name?(name), do: {n, [Macro.to_string(n) | acc]}, else: {n, acc}

        {{:., _, [_, name]}, _, args} = n, acc when is_atom(name) and is_list(args) ->
          if assertion_name?(name), do: {n, [Macro.to_string(n) | acc]}, else: {n, acc}

        n, acc ->
          {n, acc}
      end)

    Enum.reverse(acc)
  end

  defp assertion_name?(name), do: String.starts_with?(Atom.to_string(name), ["assert", "refute"])

  defp guarded?(ast) do
    {_, found} =
      Macro.prewalk(ast, false, fn
        {{:., _, [{:__aliases__, _, [:Code]}, f]}, _, _} = n, _
        when f in [:ensure_loaded?, :ensure_compiled?, :ensure_compiled, :ensure_loaded] ->
          {n, true}

        n, acc ->
          {n, acc}
      end)

    found
  end

  # ---- JS (line based) ----

  @js_title ~r/^\s*(test|it|describe)(\.\w+)?\(\s*(['"`])(.*?)\3/
  @js_assert ~r/\b(assert(\.\w+)?\s*\(|expect\s*\()/

  defp js(body) do
    lines = String.split(body, "\n")

    module_skip =
      Enum.any?(lines, &String.match?(&1, ~r/^\s*(describe|test)\.(skip|todo)\b.*\bfile\b/))

    entries =
      lines
      |> Enum.with_index()
      |> Enum.flat_map(fn {l, i} ->
        case Regex.run(@js_title, l) do
          [_, kind, mod, _q, title] ->
            skipped =
              mod in [".skip", ".todo"] or
                String.match?(l, ~r/\{[^}]*\b(skip|todo)\s*:\s*(?!false)/)

            [%{kind: kind, title: title, i: i, skipped: skipped}]

          _ ->
            []
        end
      end)

    tests =
      for {e, idx} <- Enum.with_index(entries), e.kind in ["test", "it"] do
        next =
          case Enum.at(entries, idx + 1) do
            nil -> length(lines)
            n -> n.i
          end

        span = lines |> Enum.slice(e.i + 1, max(next - e.i - 1, 0))

        asserts =
          Enum.filter(span, &String.match?(&1, @js_assert))
          |> Enum.reject(&String.match?(String.trim(&1), ~r{^(//|\*)}))

        d = entries |> Enum.take(idx) |> Enum.reverse() |> Enum.find(&(&1.kind == "describe"))

        %{
          title: e.title,
          describe: d && d.title,
          skipped: e.skipped or (d != nil and d.skipped),
          tags: [],
          tag_values: %{},
          has_assert: asserts != [],
          guarded: false,
          asserts: Enum.map(asserts, &String.trim/1)
        }
      end

    %{module_skip: module_skip, tests: tests, dynamic: []}
  end
end
