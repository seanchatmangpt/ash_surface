test("every golden is 64-hex lowercase, none re-pins a t26/v2 digest, rows distinct except twins", () => {
  const digestKey = {
    contract: "elixirDigest",
    event: "elixirStateDigest",
    observation: "elixirStateDigest",
    ir: "elixirDigest",
    receipt: "elixirReceiptHash",
  };

  for (const name of TABLE_NAMES) {
    const rows = TABLES[name];
    const twins = name !== "contract" && name !== "ir"; // rows [0] and [1] are order twins
    const seen = new Map();

    for (const [index, row] of rows.entries()) {
      const digest = row[digestKey[name]];
      assert.match(digest, /^[0-9a-f]{64}$/, `${name}/${row.name}`);
      assert.equal(
        PRIOR_DIGESTS.has(digest),
        false,
        `${name}/${row.name}: re-pins a prior suite`,
      );
      const firstIndex = seen.get(digest);
      const twinPair = twins && index === 1 && firstIndex === 0;
      assert.ok(
        firstIndex === undefined || twinPair,
        `${name}/${row.name}: unexpected digest duplicate of row ${firstIndex}`,
      );
      seen.set(digest, index);
    }
  }
});

test("order-twin rows agree: canonical sort erases insertion order in every table", () => {
  assert.equal(TABLES.event[0].elixirStateDigest, TABLES.event[1].elixirStateDigest);
  assert.equal(TABLES.observation[0].elixirStateDigest, TABLES.observation[1].elixirStateDigest);
  assert.equal(TABLES.receipt[0].elixirReceiptHash, TABLES.receipt[1].elixirReceiptHash);
});

test("deep key-order permutation never moves any digest in any table", () => {
  for (const fixture of TABLES.contract) {
    const client = createClient({ contract: reverseKeyOrder(JSON.parse(JSON.stringify(fixture.contract))) });
    assert.equal(canonicalTermDigest(client.contract), fixture.elixirDigest, fixture.name);
  }
  for (const fixture of TABLES.event) {
    const subject = fixture.subjectRef;
    const preimage = `${subject}:${fixture.sequence}:${fixture.eventType}:${canonicalJson(reverseKeyOrder(fixture.payload))}`;
    assert.equal(sha256Hex(preimage), fixture.elixirStateDigest, fixture.name);
  }
  for (const fixture of TABLES.observation) {
    const preimage = `${fixture.exactSubject}:${canonicalJson(reverseKeyOrder(fixture.facts))}`;
    assert.equal(sha256Hex(preimage), fixture.elixirStateDigest, fixture.name);
  }
  for (const fixture of TABLES.ir) {
    assert.equal(canonicalTermDigest(reverseKeyOrder(fixture.sections)), fixture.elixirDigest, fixture.name);
  }
  for (const fixture of TABLES.receipt) {
    assert.equal(sha256Hex(canonicalJson(reverseKeyOrder(fixture.payload))), fixture.elixirReceiptHash, fixture.name);
  }
});

test("sensitivity: any single content mutation flips the digest in every table", () => {
  // T1 contract
  const mutatedContract = JSON.parse(JSON.stringify(TABLES.contract[0].contract));
  mutatedContract.surface.profile.glyphs[0] = "αα";
  assert.notEqual(canonicalTermDigest(mutatedContract), TABLES.contract[0].elixirDigest);

  // T2 event
  const mutatedPayload = reverseKeyOrder(TABLES.event[0].payload);
  mutatedPayload.string = "héllo ✗";
  assert.notEqual(
    sha256Hex(`${TABLES.event[0].subjectRef}:${TABLES.event[0].sequence}:${TABLES.event[0].eventType}:${canonicalJson(mutatedPayload)}`),
    TABLES.event[0].elixirStateDigest,
  );

  // T3 observation
  const mutatedFacts = reverseKeyOrder(TABLES.observation[0].facts);
  mutatedFacts.score = 0.25;
  assert.notEqual(
    sha256Hex(`${TABLES.observation[0].exactSubject}:${canonicalJson(mutatedFacts)}`),
    TABLES.observation[0].elixirStateDigest,
  );

  // T4 ir
  const mutatedSections = reverseKeyOrder(TABLES.ir[2].sections);
  mutatedSections.actions["Σ🜂#capability"].glyph = "Σ🜂✗";
  assert.notEqual(canonicalTermDigest(mutatedSections), TABLES.ir[2].elixirDigest);

  // T5 receipt
  const mutatedReceipt = reverseKeyOrder(TABLES.receipt[0].payload);
  mutatedReceipt.dispatchState = "unknown_after_dispatch";
  assert.notEqual(sha256Hex(canonicalJson(mutatedReceipt)), TABLES.receipt[0].elixirReceiptHash);
});
