/**
 * Cross-language digest parity tables (chicago-digest-parity-051).
 *
 * ONE suite covering EVERY digest-bearing contract that exists on this base:
 * per contract, the JS twin recomputes each Elixir digest from the canonical
 * JSON in the fixture artifact, and the parity table is printed as part of the
 * test output (observable artifact, not an internal claim).
 *
 * Fixture subject: `test/js/fixtures/digest_cross_language_fixtures.json` —
 * byte-frozen output of the REAL Elixir pipeline, generated by
 * `AshSurface.DigestParityFixtures` (test/support) and pinned on the Elixir
 * side by `AshSurface.DigestParityFixtureTest` (on-disk bytes == fresh
 * pipeline encoding). The JS side reads exactly those committed bytes.
 *
 * Tables (fixture rows -> law under test):
 *
 *   T1 contract    — AshSurface.from_manifest/2 surface digest: the frozen
 *                    canon (canonical_term -> :erlang.term_to_binary ->
 *                    SHA-256, lower hex) over the contract map. Recomputed
 *                    from the fixture contract JSON by the ETF twin below,
 *                    and again over the runtime-held contract after the real
 *                    Zod parse (createClient).
 *   T2 event       — AshSurface.Event.create/4 state digest:
 *                    sha256("subject:sequence:type:" + canonicalJson(payload))
 *                    plus the ev_ content id derived from the first 32 hex.
 *   T3 observation — AshSurface.Observation.create/3 state digest:
 *                    sha256("subject:" + canonicalJson(facts)) plus the obs_
 *                    content id.
 *   T4 ir          — AshSurface.IR.Codec.from_map/1 digest over the
 *                    five-section staging IR (same frozen ETF canon over a
 *                    JSON-isomorphic preimage).
 *   T5 receipt     — the runtime receipt-hash law: sha256 over canonical JSON
 *                    of the receipt payload (Elixir twin:
 *                    AshSurface.CanonicalJSON.sha256_hex/1; JS twin: the
 *                    canonicalJson twin below, same law as the consumer e2e
 *                    runner's canonicalStringify).
 *
 * Canonical-JSON twin law (AshSurface.CanonicalJSON): maps encode as
 * recursively string-keyed, key-sorted (UTF-8 byte order) JSON objects; list
 * order is semantic and preserved; scalars verbatim.
 *
 * ETF twin law (the frozen canonical-term canon): maps become key-sorted
 * lists of 2-tuples; lists map element-wise; leaves pass through; encoded in
 * the Erlang external term format (BIT_BINARY 0x6d, SMALL_ATOM_UTF8 0x77 for
 * nil/true/false, SMALL_INTEGER 0x61, INTEGER 0x62, SMALL_BIG 0x6e,
 * NEW_FLOAT 0x46, NIL 0x6a, LIST 0x6c, SMALL_TUPLE 0x68).
 *
 * Sibling-note (merge-time extension): episode (036) and the full receipt
 * digest law (038) land on sibling branches; the suite grows a table per
 * integrated law — the fixture document is the single place rows are added.
 *
 * Falsifier (executed, recorded in the ticket History): diverging the JS
 * canonicalizer (key-sort disabled) turns every table RED; restoring turns
 * GREEN.
 */

