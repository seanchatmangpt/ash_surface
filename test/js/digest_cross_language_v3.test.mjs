/** Reverses key insertion order at every object depth (arrays mapped through). */
function reverseKeyOrder(value) {
  if (Array.isArray(value)) return value.map(reverseKeyOrder);
  if (value !== null && typeof value === "object") {
    const reversed = {};
    for (const key of Object.keys(value).reverse()) reversed[key] = reverseKeyOrder(value[key]);
    return reversed;
  }
  return value;
}

function printParityTable(title, rows) {
  console.log(`\nparity table — ${title}`);
  console.table(
    rows.map((row) => ({
      fixture: row.fixture,
      elixir: row.elixir,
      jsRecomputed: row.js,
      parity: row.elixir === row.js ? "MATCH" : "DIVERGED",
    })),
  );
}

function assertTableParity(title, rows) {
  for (const row of rows) {
    assert.equal(
      row.js,
      row.elixir,
      `${title} / ${row.fixture}: JS twin recomputed ${row.js}, Elixir froze ${row.elixir}`,
    );
  }
  printParityTable(title, rows);
}

