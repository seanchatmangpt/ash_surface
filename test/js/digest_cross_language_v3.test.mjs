const TABLES = FIXTURES.tables;
const TABLE_NAMES = ["contract", "event", "observation", "ir", "receipt"];

test("fixture artifact carries all five parity tables", () => {
  assert.deepEqual(Object.keys(TABLES).sort(), TABLE_NAMES.slice().sort());
  for (const name of TABLE_NAMES) assert.ok(TABLES[name].length >= 2, `${name}: rows present`);
});

test("T1 contract: JS twin recomputes every Elixir surface digest from the contract JSON", () => {
  const rows = TABLES.contract.map((fixture) => {
    const raw = canonicalTermDigest(JSON.parse(JSON.stringify(fixture.contract)));
    const client = createClient({ contract: JSON.parse(JSON.stringify(fixture.contract)) });
    assert.equal(client.runtimeVersion, "26.9.17", `${fixture.name}: runtime version`);
    const held = canonicalTermDigest(client.contract);
    assert.equal(held, raw, `${fixture.name}: runtime-held contract digests identically`);
    return { fixture: fixture.name, elixir: fixture.elixirDigest, js: held };
  });
  assertTableParity("T1 contract (AshSurface.from_manifest/2 surface digest)", rows);
});

test("T2 event: JS twin recomputes every state digest and ev_ content id", () => {
  const rows = TABLES.event.map((fixture) => {
    const preimage = `${fixture.subjectRef}:${fixture.sequence}:${fixture.eventType}:${canonicalJson(fixture.payload)}`;
    const digest = sha256Hex(preimage);
    assert.equal(
      "ev_" + digest.slice(0, 16),
      fixture.elixirEventId,
      `${fixture.name}: event id derives from the digest (first 16 hex chars)`,
    );
    return { fixture: fixture.name, elixir: fixture.elixirStateDigest, js: digest };
  });
  assertTableParity("T2 event (AshSurface.Event.create/4 state digest)", rows);
});

test("T3 observation: JS twin recomputes every state digest and obs_ content id", () => {
  const rows = TABLES.observation.map((fixture) => {
    const preimage = `${fixture.exactSubject}:${canonicalJson(fixture.facts)}`;
    const digest = sha256Hex(preimage);
    assert.equal(
      "obs_" + digest.slice(0, 16),
      fixture.elixirObservationId,
      `${fixture.name}: observation id derives from the digest (first 16 hex chars)`,
    );
    return { fixture: fixture.name, elixir: fixture.elixirStateDigest, js: digest };
  });
  assertTableParity("T3 observation (AshSurface.Observation.create/3 state digest)", rows);
});

test("T4 ir: JS twin recomputes every staging-IR digest over the five-section map", () => {
  const rows = TABLES.ir.map((fixture) => ({
    fixture: fixture.name,
    elixir: fixture.elixirDigest,
    js: canonicalTermDigest(fixture.sections),
  }));
  assertTableParity("T4 ir (AshSurface.IR.Codec.from_map/1 staging digest)", rows);
});

test("T5 receipt: JS twin re-derives every receipt hash from the canonical payload", () => {
  const rows = TABLES.receipt.map((fixture) => ({
    fixture: fixture.name,
    elixir: fixture.elixirReceiptHash,
    js: sha256Hex(canonicalJson(fixture.payload)),
  }));
  assertTableParity("T5 receipt (runtime receipt-hash law, CanonicalJSON twin)", rows);
});

